package com.cosplay.archive.model;

public class IndexStatsDTO {
	private int totalPosts;
	private int totalYears;
	private int totalCosplays;

	public int getTotalPosts() {
		return totalPosts;
	}
	public void setTotalPosts(int totalPosts) {
		this.totalPosts = totalPosts;
	}
	public int getTotalYears() {
		return totalYears;
	}
	public void setTotalYears(int totalYears) {
		this.totalYears = totalYears;
	}
	public int getTotalCosplays() {
		return totalCosplays;
	}
	public void setTotalCosplays(int totalCosplays) {
		this.totalCosplays = totalCosplays;
	}

}
