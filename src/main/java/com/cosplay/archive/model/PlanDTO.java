package com.cosplay.archive.model;

public class PlanDTO {
	private int plan_id;
	private String plan_file;
	private String plan_name;
	private String plan_comment;
	private String plan_switch;
	private String plan_day;
	
	public int getPlan_id() {
		return plan_id;
	}
	public void setPlan_id(int plan_id) {
		this.plan_id = plan_id;
	}
	public String getPlan_file() {
		return plan_file;
	}
	public void setPlan_file(String plan_file) {
		this.plan_file = plan_file;
	}
	public String getPlan_name() {
		return plan_name;
	}
	public void setPlan_name(String plan_name) {
		this.plan_name = plan_name;
	}
	public String getPlan_comment() {
		return plan_comment;
	}
	public void setPlan_comment(String plan_comment) {
		this.plan_comment = plan_comment;
	}
	public String getPlan_switch() {
		return plan_switch;
	}
	public void setPlan_switch(String plan_switch) {
		this.plan_switch = plan_switch;
	}
	public String getPlan_day() {
		return plan_day;
	}
	public void setPlan_day(String plan_day) {
		this.plan_day = plan_day;
	}

}
