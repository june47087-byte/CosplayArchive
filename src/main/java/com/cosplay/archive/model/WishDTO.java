package com.cosplay.archive.model;

public class WishDTO {
	private int wish_id;
	private String wish_name;
	private String wish_file;
	private String wish_comment;
	private String wish_switch;

	public int getWish_id() {
		return wish_id;
	}
	public void setWish_id(int wish_id) {
		this.wish_id = wish_id;
	}
	public String getWish_name() {
		return wish_name;
	}
	public void setWish_name(String wish_name) {
		this.wish_name = wish_name;
	}
	public String getWish_file() {
		return wish_file;
	}
	public void setWish_file(String wish_file) {
		this.wish_file = wish_file;
	}
	public String getWish_comment() {
		return wish_comment;
	}
	public void setWish_comment(String wish_comment) {
		this.wish_comment = wish_comment;
	}
	public String getWish_switch() {
		return wish_switch;
	}
	public void setWish_switch(String wish_switch) {
		this.wish_switch = wish_switch;
	}

}
